def font_tile(ch):
    g = FONT[ch]
    rows = []
    for y in range(8):
        bits = 0
        if y < 7:
            for x in range(5):
                if g[y][x] == '#':
                    bits |= 1 << (7 - (x + 1))
        rows.append(bits)
    return rows


def font_colors(ch):
    if ch == '$':
        return [(8, 1), (8, 1), (11, 1), (8, 1), (5, 1), (5, 1), (8, 1), (1, 1)]
    if ch in '0123456789':
        return [(15, 1)] * 8
    return [(15, 1), (15, 1), (15, 1), (15, 1), (15, 1), (14, 1), (14, 1), (1, 1)]


def art8(lines):
    rows = []
    for y in range(8):
        s = lines[y] if y < len(lines) else '........'
        bits = 0
        for x in range(8):
            if x < len(s) and s[x] not in '. ':
                bits |= 1 << (7 - x)
        rows.append(bits)
    return rows


def art_to_tiles(art):
    h = len(art)
    w = max(len(r) for r in art)
    out = []
    for ty in range(0, h, 8):
        for tx in range(0, w, 8):
            sub = []
            for y in range(8):
                row = art[ty + y] if (ty + y) < h else ''
                seg = row[tx:tx + 8].ljust(8, '.')
                sub.append(seg)
            out.append(art8(sub))
    return out



# ----------------------------------------------------------------------------
# Full-Screen Mode-2 3-Bank Pixel-Art Canvas Engine
# ----------------------------------------------------------------------------
class Mode2Canvas:
    def __init__(self):
        self.px = [[1] * 256 for _ in range(192)]

    def put(self, x, y, c):
        if 0 <= x < 256 and 0 <= y < 192 and c != 0:
            self.px[y][x] = c

    def rect(self, x0, y0, w, h, c):
        for y in range(y0, y0 + h):
            for x in range(x0, x0 + w):
                self.put(x, y, c)

    def frame_box(self, x0, y0, w, h, border_c=7, fill_c=1):
        self.rect(x0, y0, w, h, border_c)
        self.rect(x0 + 2, y0 + 2, w - 4, h - 4, fill_c)

    def girder_bar(self, x0, x1, y0, c_top=9, c_mid=8, c_bot=6):
        for x in range(x0, x1):
            self.put(x, y0, c_top)
            self.put(x, y0 + 1, c_mid)
            if (x // 2) % 3 == 0:
                self.put(x, y0 + 2, c_mid)
                self.put(x, y0 + 5, c_mid)
            else:
                self.put(x, y0 + 3, c_bot)
                self.put(x, y0 + 4, c_bot)
            self.put(x, y0 + 6, c_top)
            self.put(x, y0 + 7, c_bot)

    def ladder_bar(self, cx, y0, y1, col=7):
        x = cx * 8
        for y in range(y0, y1):
            self.put(x + 1, y, col)
            self.put(x + 6, y, col)
            if (y % 4) == 1:
                for dx in range(1, 7):
                    self.put(x + dx, y, col)

    def stamp_art(self, x0, y0, art, cmap, scale=1):
        for ay, row in enumerate(art):
            for ax, ch in enumerate(row):
                if ch in cmap:
                    c = cmap[ch]
                    for sy in range(scale):
                        for sx in range(scale):
                            self.put(x0 + ax * scale + sx, y0 + ay * scale + sy, c)

    def stamp_mario(self, x0, y0, left=False):
        m_art = MARIO_HEAD_R + MARIO_BODIES_R['stand']
        if left:
            m_art = hflip16(m_art)
        for y in range(16):
            for x in range(16):
                if m_art[y][x] != '.':
                    col = 8 if y < 3 else (11 if y < 8 else 5)
                    self.put(x0 + x, y0 + y, col)

    def stamp_pauline(self, x0, y0, pose='p2'):
        p_art = PAULINE_POSES[pose]
        for y in range(16):
            for x in range(16):
                if p_art[y][x] != '.':
                    col = 11 if y < 7 else 13
                    self.put(x0 + x, y0 + y, col)

    def draw_big_letter(self, x0, y0, ch, scale_x=3, scale_y=3, fg_top=8, fg_mid=9, fg_hi=11, shadow=4):
        if ch not in FONT or ch == ' ':
            return
        g = FONT[ch]
        for gy in range(7):
            for gx in range(5):
                if g[gy][gx] == '#':
                    self.rect(x0 + gx * scale_x + 2, y0 + gy * scale_y + 2, scale_x, scale_y, shadow)
        for gy in range(7):
            c = fg_hi if gy == 0 else (fg_top if gy < 3 else fg_mid)
            for gx in range(5):
                if g[gy][gx] == '#':
                    self.rect(x0 + gx * scale_x, y0 + gy * scale_y, scale_x, scale_y, c)
                    if gy % 2 == 1 and scale_x >= 3:
                        self.put(x0 + gx * scale_x + 1, y0 + gy * scale_y + 1, 15)

    def compile_banks(self, max_unique=186):
        nametable = []
        banks = []
        for third in range(3):
            tile_map = {((0,) * 8, ((1, 1),) * 8): 0}
            pats = [[0] * 8]
            cols = [[(1, 1)] * 8]
            for ty in range(third * 8, third * 8 + 8):
                for tx in range(32):
                    tp = []
                    tc = []
                    for dy in range(8):
                        strip = self.px[ty * 8 + dy][tx * 8:tx * 8 + 8]
                        counts = {}
                        for p in strip:
                            counts[p] = counts.get(p, 0) + 1
                        ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))
                        if len(ranked) == 1:
                            fg = ranked[0][0]
                            bg = 1
                            bits = 0x00 if fg == 1 else 0xFF
                            if fg == 1:
                                fg = 15
                        else:
                            c1, c2 = ranked[0][0], ranked[1][0]
                            bg, fg = (c1, c2) if c1 == 1 else ((c2, c1) if c2 == 1 else (c2, c1))
                            bits = 0
                            for bx, p in enumerate(strip):
                                use_fg = (p == fg) or (p != bg and abs(p - fg) <= abs(p - bg))
                                if use_fg:
                                    bits |= 1 << (7 - bx)
                        tp.append(bits)
                        tc.append((fg, bg))
                    key = (tuple(tp), tuple(tc))
                    if key not in tile_map:
                        if len(pats) <= max_unique:
                            tile_map[key] = len(pats)
                            pats.append(tp)
                            cols.append(tc)
                        else:
                            best_i, best_d = 0, 10**9
                            for ei in range(len(pats)):
                                d = sum(bin(tp[r] ^ pats[ei][r]).count('1') for r in range(8))
                                if d < best_d:
                                    best_d, best_i = d, ei
                            tile_map[key] = best_i
                    nametable.append(tile_map[key])
            banks.append((pats, cols))
        return banks, nametable



def hflip16(art16):
    return [row.ljust(16, '.')[:16][::-1] for row in art16]


def rot90_16(art16):
    grid = [row.ljust(16, '.')[:16] for row in art16]
    return [''.join(grid[15 - x][y] for x in range(16)) for y in range(16)]


def split_quads(art16):
    quads = []
    for qy in range(2):
        for qx in range(2):
            sub = [art16[qy * 8 + y].ljust(16, '.')[qx * 8:qx * 8 + 8] for y in range(8)]
            quads.append(art8(sub))
    return quads


